// CHECK MISSED FRUIT AND BOMBS
game.onUpdate(function () {
    if (gameEnded) {
        return
    }
    for (let fruit3 of sprites.allOfKind(SpriteKind.Food)) {
        if (fruit3.y > 120 && fruit3.vy > 0) {
            fruit3.destroy()
            info.changeLifeBy(-1)
        }
    }
    for (let bomb3 of sprites.allOfKind(BombKind)) {
        if (bomb3.y > 125) {
            bomb3.destroy()
        }
    }
    if (info.life() <= 0) {
        gameEnded = true
        game.over(false)
    }
})
// SPAWN OBJECTS
