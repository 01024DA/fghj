// SLICE WITH A BUTTON
controller.A.onEvent(ControllerButtonEvent.Pressed, function () {
    if (gameEnded) {
        return
    }
    // Check bombs first
    for (let bomb2 of sprites.allOfKind(BombKind)) {
        if (Math.abs(bomb2.x - ninja.x) < 25 && Math.abs(bomb2.y - ninja.y) < 25) {
            bomb2.destroy(effects.disintegrate)
            info.changeLifeBy(-1)
            if (info.life() <= 0) {
                gameEnded = true
                game.over(false)
            }
            return
        }
    }
    // Slice fruit
    for (let fruit2 of sprites.allOfKind(SpriteKind.Food)) {
        if (Math.abs(fruit2.x - ninja.x) < 25 && Math.abs(fruit2.y - ninja.y) < 25) {
            fruit2.destroy(effects.disintegrate)
            info.changeScoreBy(1)
            if (info.score() >= 20) {
                gameEnded = true
                game.over(true, effects.confetti)
            }
        }
    }
})
